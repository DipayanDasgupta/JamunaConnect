-- V6: public notice board, emergency contacts and first-aid reference.
-- All content is office-editable; no resident accounts are introduced.

CREATE TABLE notice (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(160)  NOT NULL,
    description VARCHAR(4000) NOT NULL,
    event_date  DATE          NOT NULL,
    link_url    VARCHAR(512),
    image_url   VARCHAR(512),
    posted_by   VARCHAR(64)   NOT NULL DEFAULT 'office',
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notice_event_date ON notice (event_date);

CREATE TABLE emergency_contact (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_title    VARCHAR(128) NOT NULL,
    phone         VARCHAR(64)  NOT NULL,
    display_order INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX idx_emergency_contact_order ON emergency_contact (display_order);

CREATE TABLE first_aid_info (
    id         INTEGER PRIMARY KEY CHECK (id = 1),
    contents   VARCHAR(4000),
    guidelines VARCHAR(4000),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

